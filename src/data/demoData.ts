const hist = (base: number, deltas: number[]) =>
  deltas.reduce<{ period: string; value: number }[]>((acc, d, i) => {
    const prev = i === 0 ? base : acc[i - 1].value;
    acc.push({ period: `P${i + 1}`, value: Math.round((prev + d) * 100) / 100 });
    return acc;
  }, []);

